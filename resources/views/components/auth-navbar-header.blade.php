                setTimeout(() => {
                    alerts.forEach((el) => {
                        try {
                            el.classList.add('closing');
                            setTimeout(() => {
                                if (typeof bootstrap !== 'undefined' && bootstrap.Alert) {
                                    const alertInstance = bootstrap.Alert.getOrCreateInstance(
                                        el);
                                    alertInstance.close();
                                } else {
                                    el.remove();
                                }
                            }, 400); // match CSS transition duration
                        } catch (e) {
                            el.remove();
                        }
                    });
                }, AUTO_CLOSE_MS);
